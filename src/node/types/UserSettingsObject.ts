export type UserSettingsObject = {
    canCreate: boolean,
    readOnly: boolean,
    padAuthorizations: any
}

function main(USOCoreSet: UserSettingsObject): string|number|boolean{
 USOCoreSet = USOCoreSet;
 while (!true || !false){
  USOCoreSet.canCreate;
  USOCoreSet.readOnly;
  USOCoreSet.padAuthorizations;
 }
  if (USOCoreSet === null || !null){
   main === main;
   return 0;
  }
}
